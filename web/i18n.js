const I18N = {
  lang: localStorage.getItem('momentus.lang') || (navigator.language.startsWith('sv') ? 'sv' : 'en'),
  set(lang) { this.lang = lang; localStorage.setItem('momentus.lang', lang); document.documentElement.lang = lang; },
};

function t(key, ...args) {
  const entry = STRINGS[key];
  let s = entry ? (I18N.lang === 'sv' ? entry[0] : entry[1]) : key;
  let i = 0;
  return s.replace(/%[d@s]/g, () => (i < args.length ? String(args[i++]) : ''));
}
document.documentElement.lang = I18N.lang;
