def _app_dir() -> Path:
    # När programmet är byggt till en .exe (PyInstaller) pekar sys.executable
    # på .exe-filen själv - vi vill leta efter .env bredvid DEN, oavsett
    # varifrån programmet råkar startas (t.ex. en genväg med annan
    # "Start in"-mapp). Körs det som vanlig .py-fil används skriptets
    # egen mapp istället.
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return Path(__file__).resolve().parent


APP_DIR = _app_dir()
_ENV_PATH = APP_DIR / ".env"
load_dotenv(dotenv_path=_ENV_PATH)

DATABASE_URL = os.environ.get("DATABASE_URL")


def _database_url() -> str:
    # Kontrollen görs här, vid anslutning, istället för vid import. Då kan den
    # som öppnar fönstret visa felet i en vanlig dialogruta, istället för att
    # programmet kraschar innan något fönster ens finns.
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise RuntimeError(
            f"Hittade ingen DATABASE_URL. Kontrollera att filen '.env' finns i: {_app_dir()}"
        )
    return url


def get_connection(use_dict_row: bool = False):
    # autocommit=True: varje sats committas direkt när den är klar, så en
    # anslutning som bara väntar (t.ex. ett öppet Lager-fönster) håller inga
    # lås i databasen. Det som måste ske "allt eller inget" lindas in i
    # "with conn.transaction():" - se t.ex. generate_article_number.
    url = _database_url()
    if use_dict_row:
        return psycopg.connect(url, autocommit=True, row_factory=dict_row)
    return psycopg.connect(url, autocommit=True)


def ensure_alive(conn, use_dict_row: bool = False):
    try:
        conn.execute("SELECT 1")
        return conn
    except Exception:
        try:
            conn.close()
        except Exception:
            pass
        return get_connection(use_dict_row=use_dict_row)


def ensure_schema(conn):
    # ALTER TABLE nedan behöver exklusivt lås på tabellen. Om någon annan
    # håller ett lås vill vi hellre få ett tydligt fel efter några sekunder
    # än ett program som hänger sig. Anslutningen kör med autocommit, så
    # inställningen gäller sessionen tills RESET längst ner i funktionen.
    conn.execute("SET lock_timeout = '5s'")

    with conn.cursor() as cur:
        cur.execute("""
        CREATE TABLE IF NOT EXISTS counters (
            prefix TEXT PRIMARY KEY,
            last INTEGER NOT NULL
        )
        """)

        cur.execute("""
        CREATE TABLE IF NOT EXISTS used_numbers (
            article_number TEXT PRIMARY KEY,
            prefix TEXT NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_used_prefix
        ON used_numbers(prefix)
        """)

        cur.execute("""
        CREATE TABLE IF NOT EXISTS sub_categories (
            k INTEGER NOT NULL,
            uu TEXT NOT NULL,
            name TEXT NOT NULL,
            PRIMARY KEY (k, uu)
        )
        """)

        cur.execute("""
        CREATE TABLE IF NOT EXISTS inventory_items (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            product_name TEXT NOT NULL,
            main_category TEXT,
            vehicle_brand TEXT,
            product_brand TEXT,
            barcode TEXT,
            org_article_no TEXT,
            oem TEXT,
            quantity INTEGER NOT NULL DEFAULT 0,
            unit_cost DOUBLE PRECISION,
            currency TEXT,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP,
            article_number TEXT,
            shelf_location TEXT
        )
        """)

        cur.execute("""
        ALTER TABLE inventory_items
        ADD COLUMN IF NOT EXISTS shelf_location TEXT
        """)

        cur.execute("""
        ALTER TABLE inventory_items
        ADD COLUMN IF NOT EXISTS last_inventory_check DATE
        """)

        cur.execute("""
        DO $$
        DECLARE
            seq_name TEXT := 'inventory_items_id_seq';
            has_default BOOLEAN := FALSE;
        BEGIN
            IF EXISTS (
                SELECT 1
                FROM information_schema.columns
                WHERE table_name = 'inventory_items'
                  AND column_name = 'id'
            ) THEN
                SELECT column_default IS NOT NULL
                INTO has_default
                FROM information_schema.columns
                WHERE table_name = 'inventory_items'
                  AND column_name = 'id';

                IF NOT has_default THEN
                    EXECUTE 'CREATE SEQUENCE IF NOT EXISTS ' || seq_name;
                    EXECUTE 'SELECT setval(''' || seq_name || ''', COALESCE((SELECT MAX(id) FROM inventory_items), 0) + 1, false)';
                    EXECUTE 'ALTER TABLE inventory_items ALTER COLUMN id SET DEFAULT nextval(''' || seq_name || ''')';
                    EXECUTE 'ALTER SEQUENCE ' || seq_name || ' OWNED BY inventory_items.id';
                END IF;
            END IF;
        END $$;
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_inventory_article_number
        ON inventory_items(article_number)
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_inventory_org_article_no
        ON inventory_items(org_article_no)
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_inventory_shelf_location
        ON inventory_items(shelf_location)
        """)

        cur.execute("""
        CREATE TABLE IF NOT EXISTS inventory_transactions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            item_id BIGINT NOT NULL,
            barcode TEXT,
            action_type TEXT NOT NULL,
            qty_change INTEGER NOT NULL,
            qty_before INTEGER NOT NULL,
            qty_after INTEGER NOT NULL,
            note TEXT,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_inventory_transactions_item_id
        ON inventory_transactions(item_id)
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_inventory_transactions_created_at
        ON inventory_transactions(created_at DESC)
        """)

        cur.execute("""
        CREATE TABLE IF NOT EXISTS saved_views (
            name TEXT PRIMARY KEY,
            columns TEXT NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP
        )
        """)

        cur.execute("""
        CREATE TABLE IF NOT EXISTS item_history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            item_id BIGINT NOT NULL,
            field_name TEXT NOT NULL,
            old_value TEXT,
            new_value TEXT,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_item_history_item_id
        ON item_history(item_id)
        """)

        # Sparade exportmallar (urval/kolumner/utseende som JSON-text).
        cur.execute("""
        CREATE TABLE IF NOT EXISTS export_presets (
            name TEXT PRIMARY KEY,
            settings TEXT NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP
        )
        """)

    # Dessa två index kan misslyckas om det redan finns dubbletter i datan.
    # Vi vill INTE att det stoppar appen från att starta - vi försöker bara
    # skapa dem tyst, och om det inte går just nu försöker vi igen nästa
    # gång programmet startar (t.ex. efter att dubbletten städats bort).
    _try_execute(
        conn,
        """
        CREATE UNIQUE INDEX IF NOT EXISTS uq_inventory_article_number_not_blank
        ON inventory_items(article_number)
        WHERE article_number IS NOT NULL AND BTRIM(article_number) <> ''
        """
    )

    _try_execute(
        conn,
        """
        CREATE UNIQUE INDEX IF NOT EXISTS uq_inventory_org_article_no_not_blank
        ON inventory_items(org_article_no)
        WHERE org_article_no IS NOT NULL AND BTRIM(org_article_no) <> ''
        """
    )

    # Samma självläkande mönster som ovan: om det redan finns ett ogiltigt
    # main_category-värde i datan misslyckas detta tyst, och vi försöker
    # igen nästa gång programmet startar (t.ex. efter att datan städats).
    _try_execute(
        conn,
        """
        ALTER TABLE inventory_items
        DROP CONSTRAINT IF EXISTS chk_inventory_main_category_valid
        """
    )
    _try_execute(
        conn,
        """
        ALTER TABLE inventory_items
        ADD CONSTRAINT chk_inventory_main_category_valid
        CHECK (
            main_category IS NULL
            OR BTRIM(main_category) = ''
            OR main_category IN (
                '0. MOTOR',
                '1. BRÄNSLE/AVGASSYSTEM',
                '2. ELSYSTEM/INDIKERINGSSYSTEM',
                '3. DRIVLINA',
                '4. CHASSI',
                '5. BROMSSYSTEM',
                '6. KAROSS',
                '7. ALLMÄNNA KOMPONENTER',
                '8. VÄTSKA',
                '9. HJUL'
            )
        )
        """
    )

    _ensure_lager_tables(conn)

    conn.execute("RESET lock_timeout")


