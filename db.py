def _try_execute(conn, sql):
    # Anslutningen kör med autocommit, så ett misslyckat kommando lämnar
    # inget halvfärdigt efter sig - felet kan bara sväljas.
    try:
        conn.execute(sql)
    except Exception:
        pass


def find_duplicate_values(conn, column: str, table: str = "inventory_items"):
    """Hittar värden som förekommer flera gånger i en given kolumn
    (t.ex. 'org_article_no' eller 'article_number'), utan att ändra något.
    Returnerar en lista av dicts: [{"value": ..., "count": ..., "ids": [...]}]
    """
    if column not in ("org_article_no", "article_number"):
        raise ValueError("Ogiltig kolumn för dubblettkontroll.")

    query = f"""
        SELECT BTRIM({column}) AS value, COUNT(*) AS cnt, ARRAY_AGG(id ORDER BY id) AS ids
        FROM {_check_table(table)}
        WHERE {column} IS NOT NULL AND BTRIM({column}) <> ''
        GROUP BY BTRIM({column})
        HAVING COUNT(*) > 1
        ORDER BY value
    """

    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(query)
        rows = cur.fetchall()

    return [{"value": r["value"], "count": r["cnt"], "ids": r["ids"]} for r in rows]


def load_saved_views(conn):
    """Returnerar alla sparade vyer som en lista av dicts: [{"name": ..., "columns": [...]}]"""
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute("SELECT name, columns FROM saved_views ORDER BY name")
        rows = cur.fetchall()
    return [{"name": r["name"], "columns": r["columns"].split(",") if r["columns"] else []} for r in rows]


def save_view(conn, name: str, column_keys: list):
    columns_csv = ",".join(column_keys)
    with conn.cursor() as cur:
        cur.execute(
            """
            INSERT INTO saved_views (name, columns, updated_at)
            VALUES (%s, %s, CURRENT_TIMESTAMP)
            ON CONFLICT (name) DO UPDATE
            SET columns = EXCLUDED.columns,
                updated_at = CURRENT_TIMESTAMP
            """,
            (name, columns_csv)
        )


def delete_view(conn, name: str):
    with conn.cursor() as cur:
        cur.execute("DELETE FROM saved_views WHERE name = %s", (name,))


