def _check_table(name: str) -> str:
    # Tabellnamn kan inte skickas som %s-parameter, så de sätts in i SQL-texten.
    # Därför släpps bara namn som finns i WAREHOUSES igenom.
    if name not in _KNOWN_TABLES:
        raise ValueError(f"Okänd tabell: {name}")
    return name


