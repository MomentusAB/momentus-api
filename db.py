def _extract_seq_from_article(article_number: str) -> int:
    try:
        return int(article_number.rsplit("-", 1)[1])
    except Exception:
        return 0


def _find_first_free_sequence(used_article_numbers, last_value: int) -> int:
    used_set = set()

    for article_number in used_article_numbers:
        seq = _extract_seq_from_article(article_number)
        if seq > 0:
            used_set.add(seq)

    for seq in range(1, last_value + 1):
        if seq not in used_set:
            return seq

    return last_value + 1


def generate_article_number(conn, k: str, uu: str, mmm: str) -> str:
    prefix = f"{k}-{uu}-{mmm}"

    # Allt nedan sker i en transaktion: FOR UPDATE-låset på countern hålls
    # tills blocket är klart, så två användare kan inte få samma nummer.
    # Vid fel rullas allt tillbaka automatiskt och felet skickas vidare.
    with conn.transaction():
        with conn.cursor(row_factory=tuple_row) as cur:
            cur.execute("""
            INSERT INTO counters(prefix, last)
            VALUES (%s, %s)
            ON CONFLICT (prefix) DO NOTHING
            """, (prefix, 0))

            cur.execute("""
            SELECT last
            FROM counters
            WHERE prefix = %s
            FOR UPDATE
            """, (prefix,))
            row = cur.fetchone()

            if not row:
                raise ValueError(f"Kunde inte låsa counter för prefix {prefix}.")

            last_value = int(row[0])

            cur.execute("""
            SELECT article_number
            FROM used_numbers
            WHERE prefix = %s
            ORDER BY article_number
            """, (prefix,))
            used_rows = cur.fetchall()
            used_article_numbers = [r[0] for r in used_rows]

            next_seq = _find_first_free_sequence(used_article_numbers, last_value)

            if next_seq > 999999:
                raise ValueError("Slut på löpnummer för denna kombination.")

            candidate = f"{prefix}-{next_seq:06d}"

            cur.execute("""
            INSERT INTO used_numbers(article_number, prefix)
            VALUES (%s, %s)
            """, (candidate, prefix))

            cur.execute("""
            UPDATE counters
            SET last = GREATEST(last, %s)
            WHERE prefix = %s
            """, (next_seq, prefix))

    return candidate


def log_item_changes(conn, item_id: int, changes: list, table: str = "item_history"):
    """changes: lista av (field_name, old_value, new_value)-tupler.
    Loggar bara faktiska ändringar - anropas med redan filtrerad lista.

    Committar inte själv: anropas antingen under autocommit (en sats = en
    transaktion) eller inuti ett "with conn.transaction()"-block som hör
    ihop med skrivningen av själva artikeln."""
    if not changes:
        return

    with conn.cursor(row_factory=tuple_row) as cur:
        cur.executemany(
            f"""
            INSERT INTO {_check_table(table)} (item_id, field_name, old_value, new_value)
            VALUES (%s, %s, %s, %s)
            """,
            [(item_id, field, old, new) for field, old, new in changes]
        )


def get_item_history(conn, item_id: int, table: str = "item_history"):
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT
                id,
                field_name,
                old_value,
                new_value,
                -- Kolumnen är TIMESTAMP utan tidszon och fylls av servern med
                -- CURRENT_TIMESTAMP i serverns tidszon. Här tolkas värdet tillbaka
                -- till en tidszonsmedveten tid så att klienten kan visa lokal tid.
                -- Inget i tabellen ändras.
                created_at AT TIME ZONE current_setting('TimeZone') AS created_at
            FROM {_check_table(table)}
            WHERE item_id = %s
            ORDER BY created_at DESC, id DESC
            """,
            (item_id,)
        )
        return cur.fetchall()


def delete_history_entry(conn, history_id: int, table: str = "item_history"):
    with conn.cursor() as cur:
        cur.execute(f"DELETE FROM {_check_table(table)} WHERE id = %s", (history_id,))
